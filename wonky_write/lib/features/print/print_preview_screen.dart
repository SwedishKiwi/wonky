/// The print / PDF preview route `/d/:uuid/print` (Write 07 §8.1): the PDF
/// generated by the client exporter shown in-app, settings on the side,
/// Download PDF and Print (browser print dialog, same tab).
class PrintPreviewScreen extends StatefulWidget {
  const PrintPreviewScreen({
    super.key,
    required this.services,
    required this.itemUuid,
    required this.themes,
  });

  final ShellServices services;
  final String itemUuid;
  final WriteThemeCatalog themes;

  @override
  State<PrintPreviewScreen> createState() => _PrintPreviewScreenState();
}

class _PrintPreviewScreenState extends State<PrintPreviewScreen> {
  DriveItemView? _item;
  ExportSource? _source;
  Object? _error;
  Uint8List? _pdf;
  int? _pages;
  bool _busy = false;
  WriteExportOptions _options = const WriteExportOptions();
  Timer? _debounce;
  int _generation = 0;

  ShellServices get s => widget.services;

  @override
  void initState() {
    super.initState();
    unawaited(_load());
  }

  @override
  void dispose() {
    _debounce?.cancel();
    super.dispose();
  }

  void _back() => s.router.go('/d/${widget.itemUuid}');

  Future<void> _load() async {
    try {
      final client = s.client;
      if (client == null) throw StateError('No server connection');
      final item = await s.drive.get(UuidValue.withValidation(widget.itemUuid));
      final docUuid = item.contentRef;
      if (docUuid == null) throw StateError('This is not a document');
      final info = await client.document.getInfo(docUuid);
      final snap = await client.document.getSnapshot(docUuid, null);
      final meta = WriteDocumentMeta.fromView(info.meta);
      final userTheme = s.prefs.writeDefaults['themeUuid'] as String?;
      final themeId =
          meta.themeUuid ?? userTheme ?? BuiltinThemes.wonkyDefault.uuid;
      final theme =
          (await widget.themes.load(themeId))?.data ??
          BuiltinThemes.wonkyDefault.theme;
      final decoded = jsonDecode(snap.deltaJson);
      final delta = Delta.fromJson(decoded is List ? decoded : const []);
      if (!mounted) return;
      setState(() {
        _item = item;
        _source = ExportSource(
          documentUuid: widget.itemUuid,
          delta: delta.isEmpty ? (Delta()..insert('\n')) : delta,
          title: item.name.isEmpty ? 'Untitled document' : item.name,
          theme: theme,
          pageSetup: meta.pageSetup,
          revision: snap.revision,
          authorName: item.owner.displayName,
          language: meta.language,
          frontMatter: meta.frontMatter,
          description: item.description,
          createdAt: item.createdAt,
          modifiedAt: item.modifiedAt,
        );
      });
      await _render();
    } catch (e) {
      if (mounted) setState(() => _error = e);
    }
  }

  Future<void> _render() async {
    final src = _source;
    if (src == null) return;
    final gen = ++_generation;
    setState(() => _busy = true);
    final resolver = imageResolverFor(s, widget.itemUuid);
    try {
      final artifact = await WriteExporter(
        images: resolver,
        fonts: WriteDocumentController.fonts,
        origin: Uri.base.hasAuthority ? Uri.base.origin : '',
      ).export(src, WriteDownloadFormat.pdf, options: _options);
      if (!mounted || gen != _generation) return;
      setState(() {
        _pdf = artifact.bytes;
        _pages = artifact.pageCount;
        _busy = false;
      });
    } catch (e) {
      if (mounted && gen == _generation) {
        setState(() {
          _error = e;
          _busy = false;
        });
      }
    } finally {
      resolver.dispose();
    }
  }

  void _setOptions(WriteExportOptions o) {
    setState(() => _options = o);
    _debounce?.cancel();
    _debounce = Timer(const Duration(milliseconds: 300), _render);
  }

  Future<void> _download() async {
    final pdf = _pdf;
    final src = _source;
    if (pdf == null || src == null) return;
    await saveArtifact(
      ExportArtifact(
        fileName: '${sanitizeFileName(src.title)}.pdf',
        mimeType: 'application/pdf',
        bytes: pdf,
        pageCount: _pages,
      ),
    );
  }

  Future<void> _print() async {
    final pdf = _pdf;
    if (pdf == null) return;
    final ok = await printPdf(pdf, title: _source?.title ?? 'Document');
    if (!ok) {
      s.toasts.show(
        'Printing isn’t available here',
        description: 'Download the PDF and print it from your PDF viewer.',
        actionLabel: 'Download PDF',
        onAction: () => unawaited(_download()),
      );
    }
  }

  bool get _canExport =>
      _item == null || _item!.canDownload || _item!.myRole.canEdit;

  @override
  Widget build(BuildContext context) {
    final theme = ShadTheme.of(context);
    final cs = theme.colorScheme;
    return CallbackShortcuts(
      bindings: {
        const SingleActivator(LogicalKeyboardKey.escape): _back,
        const SingleActivator(LogicalKeyboardKey.keyP, meta: true): _print,
        const SingleActivator(LogicalKeyboardKey.keyP, control: true): _print,
      },
      child: Focus(
        autofocus: true,
        child: ColoredBox(
          color: cs.background,
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              _header(context),
              const ShadSeparator.horizontal(margin: EdgeInsets.zero),
              Expanded(
                child: Row(
                  crossAxisAlignment: CrossAxisAlignment.stretch,
                  children: [
                    Expanded(child: _preview(context)),
                    Container(width: 1, color: cs.border),
                    SizedBox(width: 280, child: _settings(context)),
                  ],
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

  Widget _header(BuildContext context) {
    final theme = ShadTheme.of(context);
    final title = _source?.title ?? _item?.name ?? '';
    return SizedBox(
      height: 56,
      child: Padding(
        padding: const EdgeInsets.symmetric(horizontal: 12),
        child: Row(
          children: [
            ShadButton.ghost(
              key: const ValueKey<String>('print.back'),
              leading: const Icon(LucideIcons.arrowLeft, size: 16),
              onPressed: _back,
              child: const Text('Back'),
            ),
            const SizedBox(width: 8),
            Expanded(
              child: Text(
                title.isEmpty ? 'Print preview' : 'Print preview — $title',
                overflow: TextOverflow.ellipsis,
                style: theme.textTheme.large,
              ),
            ),
            if (_busy)
              const Padding(
                padding: EdgeInsets.only(right: 12),
                child: ShadSpinner(size: 16),
              ),
            ShadButton.outline(
              key: const ValueKey<String>('print.download'),
              enabled: _pdf != null && _canExport,
              leading: const Icon(LucideIcons.download, size: 16),
              onPressed: _download,
              child: const Text('Download PDF'),
            ),
            const SizedBox(width: 8),
            ShadButton(
              key: const ValueKey<String>('print.print'),
              enabled: _pdf != null && _canExport,
              leading: const Icon(LucideIcons.printer, size: 16),
              onPressed: _print,
              child: const Text('Print'),
            ),
          ],
        ),
      ),
    );
  }

  Widget _preview(BuildContext context) {
    final cs = ShadTheme.of(context).colorScheme;
    if (_error != null) {
      return WonkyEmptyState(
        illustration: isOfflineError(_error!)
            ? EmptyIllustration.offline
            : EmptyIllustration.error,
        title: 'The preview could not be created',
        description: errorMessage(_error!),
        actions: [
          ShadButton.outline(
            onPressed: () {
              setState(() => _error = null);
              unawaited(_source == null ? _load() : _render());
            },
            child: const Text('Try again'),
          ),
        ],
      );
    }
    if (!_canExport) {
      return const WonkyEmptyState(
        illustration: EmptyIllustration.error,
        title: 'The owner turned off printing and downloads',
        description: 'Ask an editor for a copy.',
      );
    }
    final pdf = _pdf;
    if (pdf == null) {
      return ColoredBox(
        color: cs.canvas,
        child: const Center(child: ShadSpinner()),
      );
    }
    return ColoredBox(
      color: cs.canvas,
      child: PdfView(
        key: const ValueKey<String>('print.preview'),
        bytes: pdf,
        pageCount: _pages,
      ),
    );
  }

  Widget _settings(BuildContext context) {
    final theme = ShadTheme.of(context);
    final o = _options;
    Widget label(String t) => Padding(
      padding: const EdgeInsets.only(top: 16, bottom: 6),
      child: Text(t, style: theme.textTheme.small),
    );
    return ListView(
      padding: const EdgeInsets.all(16),
      children: [
        Text('Settings', style: theme.textTheme.large),
        if (_pages != null) ...[
          const SizedBox(height: 4),
          Text(
            _pages == 1 ? '1 page' : '$_pages pages',
            key: const ValueKey<String>('print.pages'),
            style: theme.textTheme.muted,
          ),
        ],
        label('Colors'),
        ShadRadioGroup<ThemeVariant>(
          initialValue: o.variant,
          onChanged: (v) => _setOptions(o.copyWith(variant: v)),
          items: const [
            ShadRadio(
              key: ValueKey<String>('print.light'),
              value: ThemeVariant.light,
              label: Text('Light'),
            ),
            ShadRadio(
              key: ValueKey<String>('print.dark'),
              value: ThemeVariant.dark,
              label: Text('Dark'),
            ),
          ],
        ),
        label('Suggestions'),
        ShadSelect<SuggestionViewMode>(
          initialValue: o.suggestions,
          minWidth: 240,
          options: const [
            ShadOption(
              value: SuggestionViewMode.accepted,
              child: Text('As if accepted'),
            ),
            ShadOption(
              value: SuggestionViewMode.original,
              child: Text('Original'),
            ),
          ],
          selectedOptionBuilder: (context, v) => Text(
            v == SuggestionViewMode.original ? 'Original' : 'As if accepted',
          ),
          onChanged: (v) {
            if (v != null) _setOptions(o.copyWith(suggestions: v));
          },
        ),
        const SizedBox(height: 16),
        ShadCheckbox(
          key: const ValueKey<String>('print.headerFooter'),
          value: o.headerFooter,
          onChanged: (v) => _setOptions(o.copyWith(headerFooter: v)),
          label: const Text('Header & footer'),
        ),
        const SizedBox(height: 10),
        ShadCheckbox(
          key: const ValueKey<String>('print.toc'),
          value: o.includeToc,
          onChanged: (v) => _setOptions(o.copyWith(includeToc: v)),
          label: const Text('Table of contents'),
        ),
        const SizedBox(height: 20),
        Text(
          'Paper size, margins and the header text come from the '
          'document’s page setup (File › Page setup…).',
          style: theme.textTheme.muted.copyWith(fontSize: 12),
        ),
      ],
    );
  }
}
