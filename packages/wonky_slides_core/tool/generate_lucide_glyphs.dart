// Generates `lib/src/icons/lucide_glyphs.g.dart` (Slides 03 §6.7, SL-14):
// the Lucide icon names of the `lucide_icons_flutter` package the app ships
// (through `shad`) with their code points, so icon elements, the icon
// picker, MCP and the PDF painter share one name → glyph map without
// depending on Flutter.
//
//   dart run tool/generate_lucide_glyphs.dart \
//     ~/.pub-cache/hosted/pub.dev/lucide_icons_flutter-<v>/lib/lucide_icons.dart
//
// Re-run after upgrading `lucide_icons_flutter`; the app's
// `lucide_icon_source_test.dart` fails when the code points drift.

import 'dart:io';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: generate_lucide_glyphs.dart <lucide_icons.dart>');
    exitCode = 64;
    return;
  }
  final file = File(args.single);
  final src = file.readAsStringSync();
  final version =
      RegExp(r'lucide_icons_flutter-([^/]+)/').firstMatch(file.path)?[1] ??
      'unknown';
  // `/// name` + `/// ![..](..)` + `static const IconData x = const
  // IconData(cp, fontFamily: 'Lucide', …` (the stroke-2 family; the weighted
  // families share the code points).
  final pattern = RegExp(
    r"///\s+([a-z0-9-]+)\n\s+///\s+!\[[^\]]*\]\([^)]*\)\n\s+static const "
    r"IconData \w+ = const IconData\((\d+),\s*fontFamily: 'Lucide',",
  );
  final byName = <String, int>{};
  for (final m in pattern.allMatches(src)) {
    byName[m[1]!] = int.parse(m[2]!);
  }
  if (byName.isEmpty) {
    stderr.writeln('No icons found in ${file.path}');
    exitCode = 1;
    return;
  }
  final names = byName.keys.toList()..sort();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_lucide_glyphs.dart from')
    ..writeln('// lucide_icons_flutter $version — do not edit.')
    ..writeln()
    ..writeln("part of 'lucide_glyphs.dart';")
    ..writeln()
    ..writeln(
      '/// The `lucide_icons_flutter` version the code points come from.',
    )
    ..writeln("const lucideGlyphsVersion = '$version';")
    ..writeln()
    ..writeln('/// Lucide icon name → code point (aliases included).')
    ..writeln('const Map<String, int> _lucideCodePoints = {');
  for (final n in names) {
    out.writeln("  '$n': 0x${byName[n]!.toRadixString(16)},");
  }
  out.writeln('};');
  File(
      '${File.fromUri(Platform.script).parent.parent.path}'
      '/lib/src/icons/lucide_glyphs.g.dart',
    )
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln(
    '${names.length} names, ${byName.values.toSet().length} glyphs',
  );
}
