// Generates `lib/src/api/api_index_data.dart` (`api_index.json`, 09 §14.4)
// from the API source. Run from the package folder:
//
//   dart run tool/gen_api_index.dart
//
// `test/api/api_index_test.dart` fails when the checked-in file is stale.
import 'dart:io';

import 'package:wonky_sheets_script/src/api/api_index_builder.dart';

void main(List<String> args) {
  final out = File('lib/src/api/api_index_data.dart');
  out.writeAsStringSync(apiIndexDataSource());
  stdout.writeln('Wrote ${out.path}');
}

/// The Dart source of the data file.
String apiIndexDataSource() {
  final json = ApiIndexBuilder.build().encode();
  if (json.contains("'''")) {
    throw StateError("The API docs contain ''' (breaks the raw string).");
  }
  return '// GENERATED by tool/gen_api_index.dart from api_source.dart. '
      'Do not edit.\n'
      '// ignore_for_file: lines_longer_than_80_chars\n\n'
      '/// `api_index.json` of the Wonky Script API (09 §14.4).\n'
      "const String wonkyApiIndexJson = r'''\n$json\n''';\n";
}
