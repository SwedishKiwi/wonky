  /// Prefix of an Excel function name in OOXML storage (`_xlfn.`,
  /// `_xlfn._xlws.` or empty).
  static String excelPrefix(String upperName) {
    if (xlws.contains(upperName)) return '_xlfn._xlws.';
    if (xlfn.contains(upperName)) return '_xlfn.';
    return '';
  }

  /// Strips OOXML storage prefixes from a function name.
  static String stripPrefixes(String name) {
    var n = name;
    var changed = true;
    while (changed) {
      changed = false;
      for (final p in const ['_xlfn.', '_xlws.', '_xludf.', '_xll.']) {
        if (n.length > p.length &&
            n.substring(0, p.length).toLowerCase() == p) {
          n = n.substring(p.length);
          changed = true;
        }
      }
    }
    return n;
  }
