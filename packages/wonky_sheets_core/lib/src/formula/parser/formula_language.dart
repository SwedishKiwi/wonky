/// Localized function names and booleans of a spreadsheet display language
/// (`Spreadsheet.displayLanguage`, 04 §11.1, P2): formulas are shown and
/// typed with these names, but the **stored form stays English** and English
/// names are always accepted. Functions without a translation keep their
/// English name; error literals stay English.
final class FormulaLanguage {
  const FormulaLanguage._(
    this.code,
    this.nativeName,
    this.trueName,
    this.falseName,
    this._names,
  );

  /// Language code as stored in `Spreadsheet.displayLanguage` (`de`).
  final String code;

  /// The language's own name (`Deutsch`), for pickers.
  final String nativeName;

  /// `TRUE` / `FALSE` in this language (upper case).
  final String trueName;
  final String falseName;

  /// English canonical name → localized name (upper case).
  final Map<String, String> _names;

  static final Map<String, Map<String, String>> _reverse = {};

  /// Localized (upper case) → English canonical name.
  Map<String, String> get _toEnglish =>
      _reverse[code] ??= {for (final e in _names.entries) e.value: e.key};

  /// The localized name of English function [english] (null when it has no
  /// translation).
  String? localName(String english) => _names[english.toUpperCase()];

  /// The English name of localized function [name] (case-insensitive; null
  /// when [name] is not a localized name of this language).
  String? englishName(String name) => _toEnglish[name.toUpperCase()];

  /// The boolean value of localized literal [word], or null.
  bool? booleanOf(String word) {
    final u = word.toUpperCase();
    if (u == trueName) return true;
    if (u == falseName) return false;
    return null;
  }

  /// Every translated English name.
  Iterable<String> get translatedFunctions => _names.keys;

  /// The supported display languages (English is the default, `null`).
  static const List<FormulaLanguage> supported = [de, fr, es, sv];

  /// The language for a `displayLanguage` code (`de`, `de_DE`, `de-AT`);
  /// null for English, null and unknown codes.
  static FormulaLanguage? forCode(String? code) {
    if (code == null || code.isEmpty) return null;
    final lang = code.split(RegExp('[_-]')).first.toLowerCase();
    for (final l in supported) {
      if (l.code == lang) return l;
    }
    return null;
  }

