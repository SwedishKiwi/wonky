/// Embeds the TextMate grammars of `grammars/*.json` as Dart string constants
/// in `lib/src/grammars/` (Slides 07 §2.1), so the tokenizer works without
/// Flutter assets: on the server, in isolates and synchronously in the
/// editor.
///
/// Usage (from the package root): `dart run tool/embed_grammars.dart`.
/// `test/textmate/embedded_grammars_test.dart` fails when the embedded copy
/// is out of date.
library;

import 'dart:convert';
import 'dart:io';

void main() {
  final sources =
      Directory('grammars')
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.json'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final out = Directory('lib/src/grammars')..createSync(recursive: true);
  for (final f in out.listSync().whereType<File>()) {
    f.deleteSync();
  }

  final names = <String>[];
  for (final source in sources) {
    final name = source.uri.pathSegments.last.replaceAll('.json', '');
    names.add(name);
    final compact = jsonEncode(jsonDecode(source.readAsStringSync()));
    final quote = compact.contains("'''") ? '"""' : "'''";
    if (compact.contains(quote)) {
      stderr.writeln('$name.json contains both \'\'\' and """');
      exitCode = 1;
      return;
    }
    File('${out.path}/$name.dart').writeAsStringSync(
      '$_header'
      '/// The `$name` TextMate grammar (`grammars/$name.json`, compacted).\n'
      'const String ${_identifier(name)}Grammar =\n'
      '    r$quote$compact$quote;\n',
    );
  }

  final index = StringBuffer(_header)
    ..writeln('/// Embedded TextMate grammars by grammar id.')
    ..writeln('library;')
    ..writeln();
  for (final name in names) {
    index.writeln("import '$name.dart';");
  }
  index
    ..writeln()
    ..writeln('/// Grammar id → TextMate grammar JSON.')
    ..writeln('const Map<String, String> embeddedGrammars = {');
  for (final name in names) {
    index.writeln("  '$name': ${_identifier(name)}Grammar,");
  }
  index.writeln('};');
  File('${out.path}/grammars.dart').writeAsStringSync(index.toString());
  stdout.writeln('Embedded ${names.length} grammars into ${out.path}.');
}

const _header =
    '// GENERATED by tool/embed_grammars.dart from grammars/*.json — do not\n'
    '// edit; change the JSON (or tool/gen_grammars.py) and re-run the tool.\n'
    '// ignore_for_file: lines_longer_than_80_chars\n\n';

String _identifier(String name) {
  final parts = name.split('_');
  return parts.first +
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}
